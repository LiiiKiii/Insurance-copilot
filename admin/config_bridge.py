"""Read global, non-secret configuration and default model settings.

This bridge deliberately has no tenant input.  Every lookup is global-only;
tenant-scoped configuration needs an explicitly tenant-aware interface.
"""
from __future__ import annotations

from dataclasses import dataclass
import json
import logging
import os
import threading
import time
from typing import Any

from sqlalchemy.exc import SQLAlchemyError

from admin.services.crypto_service import (
    CredentialDecryptionError,
    EncryptionConfigurationError,
    decrypt_if_not_empty,
)

logger = logging.getLogger(__name__)

_DEFAULT_CACHE_TTL = 30
_FORBIDDEN_KEYWORDS_KEY = "compliance.forbidden_keywords"
_DISCLAIMER_KEY = "compliance.disclaimer"
_DEFAULT_FORBIDDEN_KEYWORDS = ("guarantee", "guaranteed", "must pay")
_DEFAULT_DISCLAIMER = (
    "This response is generated by AI for internal reference only and does not "
    "constitute a commitment, recommendation, or official explanation."
)


@dataclass(frozen=True)
class _StoredConfig:
    value: str
    config_type: str


@dataclass(frozen=True)
class _CacheEntry:
    stored: _StoredConfig | None
    loaded_at: float


_config_cache: dict[str, _CacheEntry] = {}
_cache_lock = threading.RLock()


class GenericConfigurationError(RuntimeError):
    """Raised when generic configuration cannot be selected safely."""


class GenericConfigurationAmbiguityError(GenericConfigurationError):
    """Raised when duplicate global records exist for one configuration key."""


class SecretConfigurationKeyError(GenericConfigurationError):
    """Raised when plaintext generic configuration is used for a secret key."""


def _validate_key(key: str) -> str:
    if not isinstance(key, str) or not key.strip():
        raise ValueError("Configuration keys must be non-empty strings.")

    from admin.models.config import is_secret_config_key

    normalized = key.strip()
    if is_secret_config_key(normalized):
        raise SecretConfigurationKeyError(
            "Secret-like configuration keys require encrypted credential storage."
        )
    return normalized


def _ttl_seconds(ttl: int) -> int:
    try:
        return max(0, int(ttl))
    except (TypeError, ValueError):
        return _DEFAULT_CACHE_TTL


def _load_global_config(key: str, ttl: int) -> _StoredConfig | None:
    """Load one global record, caching successful reads but never DB failures."""

    now = time.monotonic()
    ttl_seconds = _ttl_seconds(ttl)
    if ttl_seconds:
        with _cache_lock:
            entry = _config_cache.get(key)
            if entry is not None and now - entry.loaded_at < ttl_seconds:
                return entry.stored

    try:
        from admin.db import get_sync_db
        from admin.models.config import SystemConfig

        with get_sync_db() as db:
            rows = (
                db.query(SystemConfig)
                .filter(
                    SystemConfig.config_key == key,
                    SystemConfig.tenant_id.is_(None),
                )
                .order_by(SystemConfig.id.asc())
                .limit(2)
                .all()
            )
    except SQLAlchemyError:
        # A generic non-security setting may use its caller-provided fallback.
        # Do not include SQL or connection details in logs, and do not cache it.
        logger.warning("System configuration database lookup failed.")
        return None

    if len(rows) > 1:
        raise GenericConfigurationAmbiguityError(
            "Multiple global configuration records exist for one key."
        )

    stored = None
    if rows:
        stored = _StoredConfig(rows[0].config_value, rows[0].config_type)

    if ttl_seconds:
        with _cache_lock:
            _config_cache[key] = _CacheEntry(stored=stored, loaded_at=now)
    return stored


def _convert_by_type(stored: _StoredConfig, default: Any) -> Any:
    if stored.config_type == "string":
        return stored.value
    if stored.config_type == "int":
        try:
            return int(stored.value)
        except (TypeError, ValueError):
            return default
    if stored.config_type == "float":
        try:
            return float(stored.value)
        except (TypeError, ValueError):
            return default
    if stored.config_type == "bool":
        return _to_bool(stored.value, default)
    if stored.config_type == "json":
        try:
            return json.loads(stored.value)
        except (TypeError, ValueError, json.JSONDecodeError):
            return default
    return default


def _to_bool(value: Any, default: bool) -> bool:
    if isinstance(value, bool):
        return value
    if not isinstance(value, str):
        return default
    normalized = value.strip().casefold()
    if normalized in {"true", "1", "yes"}:
        return True
    if normalized in {"false", "0", "no"}:
        return False
    return default


def get(key: str, default: Any = None, ttl: int = _DEFAULT_CACHE_TTL) -> Any:
    """Return a global typed configuration value or ``default`` when absent."""

    stored = _load_global_config(_validate_key(key), ttl)
    return default if stored is None else _convert_by_type(stored, default)


def get_str(key: str, default: str = "") -> str:
    """Return the raw textual value for a global setting."""

    stored = _load_global_config(_validate_key(key), _DEFAULT_CACHE_TTL)
    return default if stored is None else stored.value


def get_int(key: str, default: int = 0) -> int:
    """Return a safely converted integer setting."""

    stored = _load_global_config(_validate_key(key), _DEFAULT_CACHE_TTL)
    if stored is None:
        return default
    try:
        return int(stored.value)
    except (TypeError, ValueError):
        return default


def get_float(key: str, default: float = 0.0) -> float:
    """Return a safely converted floating-point setting."""

    stored = _load_global_config(_validate_key(key), _DEFAULT_CACHE_TTL)
    if stored is None:
        return default
    try:
        return float(stored.value)
    except (TypeError, ValueError):
        return default


def get_bool(key: str, default: bool = False) -> bool:
    """Return a safely converted boolean setting."""

    stored = _load_global_config(_validate_key(key), _DEFAULT_CACHE_TTL)
    return default if stored is None else _to_bool(stored.value, default)


def get_json(key: str, default: Any = None) -> Any:
    """Return parsed JSON for a global setting, or ``default`` if malformed."""

    stored = _load_global_config(_validate_key(key), _DEFAULT_CACHE_TTL)
    if stored is None:
        return default
    try:
        return json.loads(stored.value)
    except (TypeError, ValueError, json.JSONDecodeError):
        return default


def invalidate(key: str | None = None) -> None:
    """Invalidate one global cached key, or every cached global setting."""

    with _cache_lock:
        if key is None:
            _config_cache.clear()
        else:
            _config_cache.pop(key.strip(), None)


def get_forbidden_keywords() -> list[str]:
    """Return configured compliance keywords or the conservative local default."""

    configured = get_json(_FORBIDDEN_KEYWORDS_KEY, default=list(_DEFAULT_FORBIDDEN_KEYWORDS))
    if not isinstance(configured, list) or not configured:
        return list(_DEFAULT_FORBIDDEN_KEYWORDS)

    keywords: list[str] = []
    seen: set[str] = set()
    for keyword in configured:
        if not isinstance(keyword, str) or not keyword.strip():
            return list(_DEFAULT_FORBIDDEN_KEYWORDS)
        canonical = keyword.strip()
        if canonical.casefold() not in seen:
            keywords.append(canonical)
            seen.add(canonical.casefold())
    return keywords or list(_DEFAULT_FORBIDDEN_KEYWORDS)


def get_disclaimer() -> str:
    """Return a configured disclaimer or the conservative local default."""

    disclaimer = get_str(_DISCLAIMER_KEY, default=_DEFAULT_DISCLAIMER)
    return disclaimer if disclaimer.strip() else _DEFAULT_DISCLAIMER


class DefaultModelConfigurationError(RuntimeError):
    """Raised when a selected model configuration cannot be safely used."""


class DefaultModelConfigurationAmbiguityError(DefaultModelConfigurationError):
    """Raised when multiple global default LLM configurations are eligible."""


def get_default_model_config() -> dict | None:
    """Return the enabled global default LLM configuration and resolved API key.

    A missing eligible configuration or an unavailable database preserves the
    historical ``None`` result for the briefing generator's rule-based
    fallback.  Stored credential failures are intentionally different: they
    raise a sanitized error and never fall back to environment credentials.
    """

    try:
        from admin.db import get_sync_db
        from admin.models.model_config import ModelConfig

        with get_sync_db() as db:
            rows = (
                db.query(ModelConfig)
                .filter(
                    ModelConfig.is_default.is_(True),
                    ModelConfig.model_type == "llm",
                    ModelConfig.enabled.is_(True),
                    ModelConfig.tenant_id.is_(None),
                )
                .order_by(ModelConfig.id.asc())
                .limit(2)
                .all()
            )
    except SQLAlchemyError:
        # The existing caller treats ``None`` as a signal to use its local,
        # deterministic fallback.  Do not log the database exception: it may
        # contain connection details or SQL text.
        logger.warning("Default model configuration database lookup failed.")
        return None

    if not rows:
        return None
    if len(rows) > 1:
        raise DefaultModelConfigurationAmbiguityError(
            "Multiple global default model configurations are enabled."
        )

    row = rows[0]
    if row.api_key_encrypted is None or row.api_key_encrypted == "":
        api_key = (
            os.environ.get("OPENROUTER_API_KEY")
            or os.environ.get("ANTHROPIC_API_KEY")
            or os.environ.get("OPENAI_API_KEY")
        )
    else:
        try:
            api_key = decrypt_if_not_empty(row.api_key_encrypted)
        except (CredentialDecryptionError, EncryptionConfigurationError) as exc:
            raise DefaultModelConfigurationError(
                "Stored model credential cannot be decrypted."
            ) from exc

    return {
        "id": row.id,
        "provider": row.provider,
        "model_id": row.model_id,
        "display_name": row.display_name,
        "api_key": api_key,
        "base_url": row.base_url,
        "max_tokens": row.max_tokens or 4096,
        "temperature": row.temperature if row.temperature is not None else 0.7,
    }


def get_model_for_category(category: str) -> dict | None:
    """Return the enabled global default model for ``category``.

    This mirrors the default-model bridge's global-only selection and strict
    credential handling, while permitting non-LLM categories such as embedding
    or speech models.  Ambiguous defaults are rejected rather than selected by
    order.
    """

    if not isinstance(category, str) or not category.strip():
        return None

    try:
        from admin.db import get_sync_db
        from admin.models.model_config import ModelConfig

        with get_sync_db() as db:
            rows = (
                db.query(ModelConfig)
                .filter(
                    ModelConfig.category == category.strip(),
                    ModelConfig.is_default.is_(True),
                    ModelConfig.enabled.is_(True),
                    ModelConfig.tenant_id.is_(None),
                )
                .order_by(ModelConfig.id.asc())
                .limit(2)
                .all()
            )
    except SQLAlchemyError:
        logger.warning("Model category configuration database lookup failed.")
        return None

    if not rows:
        return None
    if len(rows) > 1:
        raise DefaultModelConfigurationAmbiguityError(
            "Multiple global default model configurations are enabled for one category."
        )

    row = rows[0]
    if row.api_key_encrypted is None or row.api_key_encrypted == "":
        api_key = (
            os.environ.get("OPENROUTER_API_KEY")
            or os.environ.get("ANTHROPIC_API_KEY")
            or os.environ.get("OPENAI_API_KEY")
        )
    else:
        try:
            api_key = decrypt_if_not_empty(row.api_key_encrypted)
        except (CredentialDecryptionError, EncryptionConfigurationError) as exc:
            raise DefaultModelConfigurationError(
                "Stored model credential cannot be decrypted."
            ) from exc

    return {
        "id": row.id,
        "provider": row.provider,
        "model_id": row.model_id,
        "display_name": row.display_name,
        "api_key": api_key,
        "base_url": row.base_url,
        "max_tokens": row.max_tokens or 4096,
        "temperature": row.temperature if row.temperature is not None else 0.7,
    }
